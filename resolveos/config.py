"""Central configuration. Every value can be overridden with RESOLVEOS_* env vars
or a .env / .env.keys file in the working directory."""
from __future__ import annotations

from functools import lru_cache

from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="RESOLVEOS_", env_file=(".env", ".env.keys"), extra="ignore"
    )

    # --- infrastructure -------------------------------------------------
    database_url: str = "postgresql://resolveos@127.0.0.1:5433/resolveos"
    db_pool_size: int = 24
    api_base_url: str = "http://127.0.0.1:8080"

    # --- LLM (any OpenAI-compatible server; vLLM in our runs) -------------
    llm_mode: str = "openai"  # "openai" | "fake" (scripted, smoke tests only)
    llm_base_url: str = "http://127.0.0.1:8000/v1"
    llm_model: str = "resolveos-llm"
    llm_api_key: str = "EMPTY"
    llm_temperature: float = 0.0
    llm_max_tokens: int = 600
    llm_timeout_s: float = 90.0
    llm_retries: int = 3

    # --- API keys (generated by `python -m resolveos.db init`) ------------
    agent_api_key: str = ""
    approver_api_key: str = ""
    operator_api_key: str = ""
    admin_api_key: str = ""

    # --- agent behaviour --------------------------------------------------
    max_agent_steps: int = 14
    max_nudges: int = 2
    tool_http_timeout_s: float = 8.0
    tool_max_attempts: int = 5
    tool_backoff_base_s: float = 0.25
    max_recovery_attempts: int = 2
    breaker_threshold: int = 8
    breaker_cooldown_s: float = 3.0

    # --- policy thresholds ------------------------------------------------
    refund_auto_limit: float = 100.0
    refund_window_days: int = 30
    credit_auto_limit: float = 25.0
    credit_max: float = 200.0
    po_auto_limit: float = 2000.0
    po_max_quantity: int = 10000
    reship_approval_value: float = 300.0

    # --- worker -----------------------------------------------------------
    worker_threads: int = 8
    lease_seconds: float = 20.0
    worker_poll_s: float = 0.2
    max_workflow_attempts: int = 3
    approval_ttl_s: float = 900.0

    # --- fault injection (evaluation only) --------------------------------
    chaos_enabled: bool = False

    # --- model router: a second, "strong" OpenAI-compatible model ------------
    # e.g. Gemini: base_url=https://generativelanguage.googleapis.com/v1beta/openai/
    strong_llm_base_url: str = ""
    strong_llm_api_key: str = ""
    strong_llm_model: str = ""
    router_mode: str = "auto"          # auto | primary | strong
    llm_price_in: float = 0.0          # USD per 1M input tokens (primary)
    llm_price_out: float = 0.0
    strong_price_in: float = 0.30      # set to your provider's real prices
    strong_price_out: float = 2.50

    # --- product layer --------------------------------------------------------
    secret_key: str = ""               # signs sessions + one-tap approval links
    public_url: str = "http://127.0.0.1:8080"
    allow_signup: bool = True
    session_hours: float = 24.0
    reply_drafts: bool = True
    smtp_host: str = ""
    smtp_port: int = 587
    smtp_user: str = ""
    smtp_password: str = ""
    smtp_from: str = "support@example.com"
    slack_signing_secret: str = ""
    metrics_token: str = ""            # if set, /metrics requires ?token=
    otel_enabled: bool = False         # export OpenTelemetry traces (OTEL_EXPORTER_OTLP_ENDPOINT)


@lru_cache
def get_settings() -> Settings:
    return Settings()


settings = get_settings()
